from __future__ import annotations
import argparse, csv, json
from pathlib import Path

from catalog import load_catalog
from mapper import map_observation
from units import normalize_unit, convert_value
from comparability import classify


def main(repo_root: Path):
    exp = repo_root / "experiments/stage-04"
    data = repo_root / "testdata/synthetic/stage-04/normalization_cases.json"
    results_dir = exp / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    catalog = load_catalog(exp / "terminology_catalog.json")
    cases = json.loads(data.read_text(encoding="utf-8"))

    mapping_out = []
    status_hits = code_hits = validated_total = false_validations = 0
    for case in cases["mapping_cases"]:
        result = map_observation(case, catalog)
        status_ok = result["status"] == case["expected_status"]
        status_hits += int(status_ok)
        if case["expected_status"] == "validated":
            validated_total += 1
            code_ok = result.get("validated_code") == case["expected_code"]
            code_hits += int(code_ok)
        else:
            code_ok = True
            if result["status"] == "validated":
                false_validations += 1
        if "expected_candidates" in case:
            candidate_ok = sorted(result.get("candidate_codes",[])) == sorted(case["expected_candidates"])
        else:
            candidate_ok = True
        mapping_out.append({"id":case["id"],"expected_status":case["expected_status"],"actual_status":result["status"],"status_ok":status_ok,"code_ok":code_ok,"candidate_ok":candidate_ok,"result":result})

    unit_out = []
    unit_hits = 0
    for case in cases["unit_cases"]:
        actual = normalize_unit(case["source"])
        ok = actual == case["expected"]
        unit_hits += int(ok)
        unit_out.append({"id":case["id"],"source":case["source"],"expected":case["expected"],"actual":actual,"ok":ok})

    conv_out = []
    conv_hits = 0
    for case in cases["conversion_cases"]:
        actual = convert_value(case["value"], case["from"], case["to"])
        ok = actual["status"] == case["expected_status"]
        if case["expected_value"] is not None:
            ok = ok and abs(actual["value"] - case["expected_value"]) < 1e-9
        else:
            ok = ok and actual["value"] is None
        conv_hits += int(ok)
        conv_out.append({"id":case["id"],"expected_status":case["expected_status"],"actual":actual,"ok":ok})

    comp_out = []
    comp_hits = 0
    for case in cases["comparability_cases"]:
        actual = classify(case["left"], case["right"])
        ok = actual == case["expected"]
        comp_hits += int(ok)
        comp_out.append({"id":case["id"],"expected":case["expected"],"actual":actual,"ok":ok})

    # Stage-03 no-guess regression. Use one canonical output generated by the previous Stage.
    s3 = repo_root / "experiments/stage-03/results/canonical_outputs/digital_pipe__hybrid_auto.json"
    s3_data = json.loads(s3.read_text(encoding="utf-8"))
    s3_results = []
    no_guess = True
    for obs in s3_data["observations"]:
        synthetic_input = {
            "local_test_name": obs["local_test_name"],
            "system": "urine_sediment" if "microscopic" in obs["local_test_name"].lower() else "urine",
            "scale": None,
            "method": None,
            "unit_source": obs["result"].get("unit_source"),
        }
        result = map_observation(synthetic_input, catalog)
        if result["status"] == "validated":
            no_guess = False
        s3_results.append({"local_test_name":obs["local_test_name"],"mapping":result})

    summary = {
        "mapping_status_accuracy": status_hits / len(cases["mapping_cases"]),
        "validated_code_exact_accuracy": code_hits / validated_total,
        "false_validation_rate": false_validations / len(cases["mapping_cases"]),
        "unit_normalization_accuracy": unit_hits / len(cases["unit_cases"]),
        "safe_conversion_accuracy": conv_hits / len(cases["conversion_cases"]),
        "comparability_accuracy": comp_hits / len(cases["comparability_cases"]),
        "stage03_unknown_label_no_guess": no_guess,
    }
    payload = {"summary":summary,"mapping":mapping_out,"units":unit_out,"conversions":conv_out,"comparability":comp_out,"stage03_regression":s3_results}
    (results_dir/"benchmark.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")

    with (results_dir/"benchmark.csv").open("w", newline="", encoding="utf-8") as f:
        w=csv.writer(f); w.writerow(["metric","value"])
        for k,v in summary.items(): w.writerow([k,v])

    lines=["# Stage 04 Experiment Run Report","","## Summary","","| Metric | Value |","|---|---:|"]
    for k,v in summary.items():
        lines.append(f"| {k} | {v} |")
    lines += ["","## Interpretation","","- Ambiguous method cases remain `candidate` instead of being force-validated.","- Unknown Stage-03 synthetic labels remain non-validated.","- Exact unit conversions are allowlisted; chemistry-specific conversion is rejected.","- Comparability requires validated identity before unit conversion is considered.",""]
    (results_dir/"RUN_REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps(summary, indent=2))

if __name__ == "__main__":
    ap=argparse.ArgumentParser(); ap.add_argument("--repo-root",type=Path,default=Path(".")); args=ap.parse_args(); main(args.repo_root.resolve())
